package com.fdb.frankfurt.service;

import io.micrometer.core.instrument.Counter;
import io.micrometer.core.instrument.Gauge;
import io.micrometer.core.instrument.MeterRegistry;
import io.micrometer.core.instrument.Timer;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicLong;
import java.util.concurrent.atomic.AtomicBoolean;

/**
 * 10. Observability: central registry of custom business metrics.
 * <p>
 * All metrics are prefixed with {@code fdb.} so they stand apart from the
 * default JVM/Spring Boot metrics in Prometheus. Exposed through the
 * standard {@code /actuator/prometheus} endpoint (see application.yml).
 */
@Service
@RequiredArgsConstructor
public class MetricsService {

    private final MeterRegistry registry;
    private final OutboxRepository outboxRepository;

    private final AtomicBoolean simulatorActive = new AtomicBoolean(false);
    private final AtomicLong dlqDepth = new AtomicLong(0);
    private final AtomicLong lastTransferAmount = new AtomicLong(0);

    private final Counter transfersReceivedCounter;
    private final Counter transfersProcessedCounter;
    private final Counter transfersFailedCounter;
    private final Counter outboxPublishedCounter;
    private final Counter anomalyAlertsCounter;
    private final Counter dlqMessagesCounter;
    private final Timer transferProcessingTimer;

    public MetricsService(MeterRegistry registry, OutboxRepository outboxRepository) {
        this.registry = registry;
        this.outboxRepository = outboxRepository;

        this.transfersReceivedCounter = Counter.builder("fdb.transfers.received")
                .description("Total transfer requests received by the API")
                .register(registry);
        this.transfersProcessedCounter = Counter.builder("fdb.transfers.processed")
                .description("Total transfers successfully processed by the consumer")
                .register(registry);
        this.transfersFailedCounter = Counter.builder("fdb.transfers.failed")
                .description("Total transfers that failed during consumer processing")
                .register(registry);
        this.outboxPublishedCounter = Counter.builder("fdb.outbox.published")
                .description("Total outbox events published to Kafka")
                .register(registry);
        this.anomalyAlertsCounter = Counter.builder("fdb.anomaly.alerts")
                .description("Total anomaly alerts generated by the detector")
                .register(registry);
        this.dlqMessagesCounter = Counter.builder("fdb.dlq.messages")
                .description("Total messages that landed in the dead letter queue")
                .register(registry);
        this.transferProcessingTimer = Timer.builder("fdb.transfer.processing")
                .description("Latency of transfer processing inside the consumer")
                .register(registry);

        Gauge.builder("fdb.outbox.pending", outboxRepository, repo ->
                        repo.findAll().stream()
                                .filter(e -> e.getProcessedAt() == null)
                                .count())
                .baseUnit("events")
                .description("Number of unprocessed outbox events waiting to be published")
                .register(registry);

        Gauge.builder("fdb.simulator.running", simulatorActive, active -> active.get() ? 1.0 : 0.0)
                .description("Whether the load simulator is currently running (1 = on, 0 = off)")
                .register(registry);

        Gauge.builder("fdb.dlq.depth", dlqDepth, AtomicLong::get)
                .baseUnit("messages")
                .description("Approximate number of messages currently in the dead letter queue")
                .register(registry);

        Gauge.builder("fdb.transfer.last.amount", lastTransferAmount, AtomicLong::get)
                .baseUnit("cents")
                .description("Amount of the most recently processed transfer (scaled)")
                .register(registry);
    }

    public void recordTransferReceived() {
        transfersReceivedCounter.increment();
    }

    /**
     * Records one processing attempt. {@code success} is true when the consumer
     * finished without throwing (insufficient-funds failures are counted as
     * success at the orchestration level since the transaction is marked FAILED
     * intentionally, not lost).
     */
    public void recordProcessing(long elapsedNanos, boolean success) {
        transferProcessingTimer.record(elapsedNanos, TimeUnit.NANOSECONDS);
        if (success) {
            transfersProcessedCounter.increment();
        } else {
            transfersFailedCounter.increment();
        }
    }

    public void recordOutboxPublished() {
        outboxPublishedCounter.increment();
    }

    public void recordAnomalyAlert() {
        anomalyAlertsCounter.increment();
    }

    public void recordDltMessage() {
        dlqMessagesCounter.increment();
        dlqDepth.incrementAndGet();
    }

    public void setSimulatorActive(boolean active) {
        simulatorActive.set(active);
    }

    public void recordLastTransferAmount(long scaledAmount) {
        lastTransferAmount.set(scaledAmount);
    }
}